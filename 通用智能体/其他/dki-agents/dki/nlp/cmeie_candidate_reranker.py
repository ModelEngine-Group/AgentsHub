"""Deterministic candidate-level reranking helpers for complete CMeIE SPO.

The neural model is intentionally kept outside this module.  These helpers
define the leak-resistant contract around it: candidates are exact spans
generated by a frozen extractor, one global threshold is selected on the
calibration partition, and schema conditioning is a single on/off choice.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable, Mapping, Sequence

from dki.nlp.cmeie_pair import signature_text


@dataclass(frozen=True, order=True)
class PairRerankCandidate:
    """One exact OneRel proposal converted to a surface-form SPO candidate."""

    row_index: int
    predicate_id: int
    subject: str
    predicate: str
    object: str
    marked_text: str
    relation_score: float = 0.0
    link_score: float = 0.0
    boundary_score: float = 0.0

    @property
    def triple(self) -> tuple[str, str, str]:
        return (self.subject, self.predicate, self.object)


@dataclass(frozen=True)
class PairRerankInput:
    """One classifier input associated with its source candidate."""

    candidate_index: int
    marked_text: str
    signature: str


def build_fit_surface_schema(
    rows: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    """Build a deterministic type/schema contract from fit annotations only.

    Surface types are role-specific: a mention observed only as an object is
    not silently treated as a known subject.  Ambiguous mentions retain every
    observed type and a candidate is admissible when any observed type pair is
    valid for its predicate.  This keeps the filter conservative.
    """

    subject_types: dict[str, set[str]] = {}
    object_types: dict[str, set[str]] = {}
    predicate_pairs: dict[str, set[tuple[str, str]]] = {}
    for row in rows:
        spo_list = row.get("spo_list")
        if not isinstance(spo_list, Sequence) or isinstance(
            spo_list, (str, bytes)
        ):
            raise ValueError("CMeIE row spo_list must be a sequence")
        for spo in spo_list:
            if not isinstance(spo, Mapping):
                raise ValueError("CMeIE SPO must be an object")
            subject = str(spo.get("subject", "")).strip()
            predicate = str(spo.get("predicate", "")).strip()
            obj = str(spo.get("object", "")).strip()
            subject_type = str(spo.get("subject_type", "")).strip()
            object_type = str(spo.get("object_type", "")).strip()
            if not all(
                (subject, predicate, obj, subject_type, object_type)
            ):
                raise ValueError("CMeIE SPO is missing a schema field")
            subject_types.setdefault(subject, set()).add(subject_type)
            object_types.setdefault(obj, set()).add(object_type)
            predicate_pairs.setdefault(predicate, set()).add(
                (subject_type, object_type)
            )
    return {
        "subject_types": {
            surface: sorted(values)
            for surface, values in sorted(subject_types.items())
        },
        "object_types": {
            surface: sorted(values)
            for surface, values in sorted(object_types.items())
        },
        "predicate_type_pairs": {
            predicate: [list(pair) for pair in sorted(values)]
            for predicate, values in sorted(predicate_pairs.items())
        },
    }


def surface_schema_decision(
    candidate: PairRerankCandidate,
    contract: Mapping[str, Any],
) -> tuple[bool, str]:
    """Return conservative fit-only schema admissibility and audit reason."""

    subject_map = contract.get("subject_types")
    object_map = contract.get("object_types")
    predicate_map = contract.get("predicate_type_pairs")
    if not all(isinstance(value, Mapping) for value in (subject_map, object_map, predicate_map)):
        raise ValueError("surface schema contract is malformed")
    assert isinstance(subject_map, Mapping)
    assert isinstance(object_map, Mapping)
    assert isinstance(predicate_map, Mapping)
    subject_types = tuple(str(value) for value in subject_map.get(candidate.subject, ()))
    object_types = tuple(str(value) for value in object_map.get(candidate.object, ()))
    if not subject_types or not object_types:
        return True, "unknown_surface_fail_open"
    allowed = {
        (str(pair[0]), str(pair[1]))
        for pair in predicate_map.get(candidate.predicate, ())
        if isinstance(pair, Sequence)
        and not isinstance(pair, (str, bytes))
        and len(pair) == 2
    }
    if any(
        (subject_type, object_type) in allowed
        for subject_type in subject_types
        for object_type in object_types
    ):
        return True, "known_schema_admissible"
    return False, "known_schema_rejected"


def apply_fit_surface_schema(
    candidates: Sequence[PairRerankCandidate],
    contract: Mapping[str, Any],
) -> tuple[tuple[int, ...], dict[str, int]]:
    """Return retained candidate indices plus aggregate-only audit counts."""

    retained: list[int] = []
    reasons: dict[str, int] = {}
    for index, candidate in enumerate(candidates):
        admissible, reason = surface_schema_decision(candidate, contract)
        reasons[reason] = reasons.get(reason, 0) + 1
        if admissible:
            retained.append(index)
    return tuple(retained), dict(sorted(reasons.items()))


def predicate_signature_map(
    contract: Mapping[str, Any],
    predicates: Sequence[str],
) -> dict[int, tuple[str, ...]]:
    """Return deterministic, fit-only type-signature texts per predicate.

    The relation checkpoint stores a map from ``subject_type\tobject_type``
    to admissible predicate IDs.  Reversing that map does not inspect the
    evaluated row or its labels; it is a fixed training-schema constraint.
    """

    constraints = contract.get("schema_constraints") or {}
    if not isinstance(constraints, Mapping):
        raise ValueError("schema_constraints must be an object")
    signatures: dict[int, set[str]] = {
        index: set() for index in range(len(predicates))
    }
    for raw_key, raw_ids in constraints.items():
        parts = str(raw_key).split("\t")
        if len(parts) != 2:
            raise ValueError("schema constraint key must contain one tab")
        if not isinstance(raw_ids, Sequence) or isinstance(raw_ids, (str, bytes)):
            raise ValueError("schema constraint labels must be a sequence")
        rendered = signature_text(parts[0], parts[1])
        for raw_id in raw_ids:
            try:
                predicate_id = int(raw_id)
            except (TypeError, ValueError) as error:
                raise ValueError("schema constraint label must be an integer") from error
            if not 0 <= predicate_id < len(predicates):
                raise ValueError("schema constraint label is out of range")
            signatures[predicate_id].add(rendered)
    return {
        predicate_id: tuple(sorted(values))
        for predicate_id, values in signatures.items()
    }


def expand_pair_rerank_inputs(
    candidates: Sequence[PairRerankCandidate],
    signatures_by_predicate: Mapping[int, Sequence[str]],
    *,
    schema_on: bool,
) -> tuple[PairRerankInput, ...]:
    """Expand candidates into classifier inputs without inserting gold data.

    With schema conditioning disabled the second sequence is empty.  With it
    enabled, a candidate is evaluated once for each fit-schema signature that
    admits its already-proposed predicate.  A predicate absent from the fit
    schema is fail-closed and produces no classifier input.
    """

    expanded: list[PairRerankInput] = []
    for candidate_index, candidate in enumerate(candidates):
        signatures = (
            tuple(signatures_by_predicate.get(candidate.predicate_id, ()))
            if schema_on
            else ("",)
        )
        for signature in signatures:
            expanded.append(
                PairRerankInput(
                    candidate_index=candidate_index,
                    marked_text=candidate.marked_text,
                    signature=str(signature),
                )
            )
    return tuple(expanded)


def aggregate_candidate_probabilities(
    *,
    candidates: Sequence[PairRerankCandidate],
    inputs: Sequence[PairRerankInput],
    probability_rows: Sequence[Sequence[float]],
    n_predicates: int,
) -> tuple[float, ...]:
    """Take the maximum predicate probability across admissible signatures."""

    if len(inputs) != len(probability_rows):
        raise ValueError("classifier inputs and probability rows differ")
    scores = [-1.0] * len(candidates)
    for item, probabilities in zip(inputs, probability_rows):
        if not 0 <= item.candidate_index < len(candidates):
            raise ValueError("classifier input candidate index is out of range")
        if len(probabilities) != n_predicates:
            raise ValueError("classifier probability width differs from predicates")
        predicate_id = candidates[item.candidate_index].predicate_id
        if not 0 <= predicate_id < n_predicates:
            raise ValueError("candidate predicate is out of range")
        scores[item.candidate_index] = max(
            scores[item.candidate_index], float(probabilities[predicate_id])
        )
    return tuple(scores)


def decode_pair_rerank_candidates(
    *,
    n_rows: int,
    candidates: Sequence[PairRerankCandidate],
    scores: Sequence[float],
    threshold: float,
) -> list[set[tuple[str, str, str]]]:
    """Decode exact surface triples with one global probability threshold."""

    if len(candidates) != len(scores):
        raise ValueError("candidates and scores differ")
    if not 0.0 <= threshold <= 1.0:
        raise ValueError("candidate threshold must be in [0, 1]")
    predicted: list[set[tuple[str, str, str]]] = [set() for _ in range(n_rows)]
    for candidate, score in zip(candidates, scores):
        if not 0 <= candidate.row_index < n_rows:
            raise ValueError("candidate row index is out of range")
        if float(score) >= threshold:
            predicted[candidate.row_index].add(candidate.triple)
    return predicted


def micro_spo_metric(
    gold_rows: Sequence[set[tuple[str, str, str]]],
    predicted_rows: Sequence[set[tuple[str, str, str]]],
) -> dict[str, float | int]:
    if len(gold_rows) != len(predicted_rows):
        raise ValueError("gold and predicted row counts differ")
    true_positive = sum(
        len(gold & predicted)
        for gold, predicted in zip(gold_rows, predicted_rows)
    )
    false_positive = sum(
        len(predicted - gold)
        for gold, predicted in zip(gold_rows, predicted_rows)
    )
    false_negative = sum(
        len(gold - predicted)
        for gold, predicted in zip(gold_rows, predicted_rows)
    )
    precision = true_positive / max(1, true_positive + false_positive)
    recall = true_positive / max(1, true_positive + false_negative)
    f1 = 2.0 * precision * recall / max(1e-12, precision + recall)
    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": true_positive,
        "fp": false_positive,
        "fn": false_negative,
    }


def select_global_rerank_policy(
    *,
    gold_rows: Sequence[set[tuple[str, str, str]]],
    candidates: Sequence[PairRerankCandidate],
    score_sets: Mapping[bool, Sequence[float]],
    thresholds: Iterable[float],
) -> dict[str, Any]:
    """Select only a global threshold and schema on/off on calibration."""

    grid = tuple(sorted({float(value) for value in thresholds}))
    if not grid or any(not 0.0 <= value <= 1.0 for value in grid):
        raise ValueError("threshold grid must contain values in [0, 1]")
    if set(score_sets) != {False, True}:
        raise ValueError("score sets must contain schema off and on")
    sweep: list[dict[str, Any]] = []
    for schema_on in (False, True):
        scores = score_sets[schema_on]
        for threshold in grid:
            predicted = decode_pair_rerank_candidates(
                n_rows=len(gold_rows),
                candidates=candidates,
                scores=scores,
                threshold=threshold,
            )
            sweep.append(
                {
                    "schema_on": schema_on,
                    "threshold": threshold,
                    "metric": micro_spo_metric(gold_rows, predicted),
                }
            )
    selected = max(
        sweep,
        key=lambda item: (
            item["metric"]["f1"],
            item["metric"]["precision"],
            item["threshold"],
            int(item["schema_on"]),
        ),
    )
    return {
        "schema_on": selected["schema_on"],
        "threshold": selected["threshold"],
        "metric": selected["metric"],
        "grid_size": len(sweep),
        "sweep": sweep,
    }


def build_candidate_hard_negative_groups(
    *,
    candidates: Sequence[PairRerankCandidate],
    gold_rows: Sequence[set[tuple[str, str, str]]],
    negative_ratio: int = 8,
) -> tuple[tuple[tuple[int, ...], ...], dict[str, int | float]]:
    """Group each reachable positive with deterministic proposal-hard negatives.

    Candidate generation has already supplied realistic wrong predicates,
    boundaries, directions, cross-SPO combinations and self pairs.  This
    function does not synthesize or inspect any outer/dev annotations; it only
    labels exact fit candidates and takes the highest-scoring non-gold members.
    """

    if negative_ratio < 1:
        raise ValueError("negative_ratio must be positive")
    by_row: list[list[int]] = [[] for _ in gold_rows]
    for index, candidate in enumerate(candidates):
        if not 0 <= candidate.row_index < len(gold_rows):
            raise ValueError("candidate row index is out of range")
        by_row[candidate.row_index].append(index)

    def hardness(index: int) -> tuple[float, float, float, int]:
        candidate = candidates[index]
        values = (
            float(candidate.link_score),
            float(candidate.relation_score),
            float(candidate.boundary_score),
        )
        if not all(value == value and abs(value) != float("inf") for value in values):
            raise ValueError("candidate contains a non-finite proposal score")
        return (-values[0], -values[1], -values[2], index)

    groups: list[tuple[int, ...]] = []
    reachable_gold = 0
    selected_negative_indices: set[int] = set()
    available_negative_indices: set[int] = set()
    for row_index, indices in enumerate(by_row):
        positives = sorted(
            index for index in indices if candidates[index].triple in gold_rows[row_index]
        )
        negatives = sorted(
            (index for index in indices if candidates[index].triple not in gold_rows[row_index]),
            key=hardness,
        )
        available_negative_indices.update(negatives)
        reachable_gold += len({candidates[index].triple for index in positives})
        for positive_offset, positive in enumerate(positives):
            start = positive_offset * negative_ratio
            selected_negatives = tuple(negatives[start : start + negative_ratio])
            if len(selected_negatives) < min(negative_ratio, len(negatives)):
                # Rows with more positives than disjoint negative chunks retain
                # deterministic hard-negative pressure after unique coverage.
                missing = min(negative_ratio, len(negatives)) - len(selected_negatives)
                selected_negatives += tuple(negatives[:missing])
            selected_negative_indices.update(selected_negatives)
            groups.append((positive, *selected_negatives))
    total_gold = sum(len(row) for row in gold_rows)
    return tuple(groups), {
        "n_groups": len(groups),
        "n_positive_samples": len(groups),
        "n_negative_samples": sum(len(group) - 1 for group in groups),
        "n_unique_negative_samples": len(selected_negative_indices),
        "n_available_negative_samples": len(available_negative_indices),
        "negative_candidate_coverage": len(selected_negative_indices)
        / max(1, len(available_negative_indices)),
        "negative_ratio": negative_ratio,
        "reachable_gold": reachable_gold,
        "total_gold": total_gold,
        "reachable_gold_recall": reachable_gold / max(1, total_gold),
    }
