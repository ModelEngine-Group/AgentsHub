def build() -> dict:
    """组装并校验词典。任何引用不存在的词条都会 raise。"""
    diseases = {}
    for name, (aliases, dept, symptoms, drugs, exams, treatments, comps) in DISEASES.items():
        # 一致性校验
        assert dept in DEPARTMENTS, f"{name}: 未知科室 {dept}"
        for s in symptoms:
            assert s in SYMPTOMS, f"{name}: 未知症状 {s}"
        for d in drugs:
            assert d in DRUGS, f"{name}: 未知药物 {d}"
        for e in exams:
            assert e in EXAMS, f"{name}: 未知检查 {e}"
        for t in treatments:
            assert t in TREATMENTS, f"{name}: 未知治疗 {t}"
        for c in comps:
            assert c in DISEASES, f"{name}: 未知并发疾病 {c}"
            assert c != name, f"{name}: 并发症自环"
        diseases[name] = {
            "aliases": aliases,
            "department": dept,
            "symptoms": symptoms,
            "drugs": drugs,
            "exams": exams,
            "treatments": treatments,
            "complications": comps,
        }
    # 药物禁忌指向的疾病必须存在
    for dname, (_aliases, contra) in DRUGS.items():
        for c in contra:
            assert c in DISEASES, f"药物 {dname}: 禁忌疾病 {c} 不在疾病表"

    return {
        "diseases": diseases,
        "symptoms": {k: {"aliases": v} for k, v in SYMPTOMS.items()},
        "drugs": {
            k: {"aliases": a, "contraindications": c} for k, (a, c) in DRUGS.items()
        },
        "exams": {k: {"aliases": v} for k, v in EXAMS.items()},
        "treatments": {k: {"aliases": v} for k, v in TREATMENTS.items()},
        "departments": DEPARTMENTS,
    }


def main():
    data = build()
    DICT_PATH.parent.mkdir(parents=True, exist_ok=True)
    DICT_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"词典已写出: {DICT_PATH}")
    print(
        f"疾病 {len(data['diseases'])} | 症状 {len(data['symptoms'])} | "
        f"药物 {len(data['drugs'])} | 检查 {len(data['exams'])} | "
        f"治疗 {len(data['treatments'])} | 科室 {len(data['departments'])}"
    )


if __name__ == "__main__":
    main()
