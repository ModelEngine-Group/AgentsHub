TOPICS: list[dict] = [
    {
        "code": code,
        "title": title,
        "keywords": keywords,
        "chapter_code": chapter["code"],
        "chapter_title": chapter["title"],
        "file": chapter["file"],
    }
    for chapter in CHAPTERS
    for code, title, keywords in chapter["topics"]
]

_BY_CODE = {topic["code"]: topic for topic in TOPICS}
_CHAPTER_BY_CODE = {chapter["code"]: chapter for chapter in CHAPTERS}


def chapter_of(topic_code: str) -> dict | None:
    topic = _BY_CODE.get((topic_code or "").strip().upper())
    if topic is None:
        return None
    return _CHAPTER_BY_CODE.get(topic["chapter_code"])


def locate_topic(query: str, limit: int = 3) -> dict:
    """按关键词给知识点打分排序，返回最可能的若干条。"""
    text = (query or "").strip()
    if not text:
        return {"query": text, "matches": [], "note": "查询为空，请给出知识点名称、章节或题目关键步骤"}

    lowered = text.lower()
    scored: list[tuple[int, dict]] = []

    for topic in TOPICS:
        score = 0
        reasons: list[str] = []
        if topic["code"].lower() in lowered:
            score += 100
            reasons.append("命中编号")
        if topic["title"] in text:
            score += 60
            reasons.append("命中知识点名")
        for keyword in topic["keywords"]:
            if keyword.lower() in lowered:
                score += 25
                reasons.append(f"命中关键词“{keyword}”")
        if topic["chapter_title"] in text:
            score += 15
            reasons.append("命中章节名")
        if score:
            scored.append((score, {**topic, "_score": score, "_reasons": reasons[:4]}))

    scored.sort(key=lambda item: (-item[0], item[1]["code"]))
    matches = [item for _, item in scored[: max(1, limit)]]
    return {
        "query": text,
        "matches": matches,
        "note": (
            "编号可用于引用讲义条目；若未命中，请改用知识点名称（如“等价无穷小”“分部积分”）再试一次"
            if not matches
            else "按匹配度排序，取前若干条"
        ),
    }
